/**
 * Background canvas: always a muted, looped YouTube video. Uses the song's own
 * video first; otherwise picks a random real music video from a pool built by
 * searching "<artist(s)> official music video" (no song title, so static
 * cover-art uploads are avoided). Purely decorative and never receives taps.
 */
import { useEffect, useRef, useState } from "react";
import { cn } from "@/lib/utils";
import { searchYouTubeVideos } from "@/services/musicApi";
import { usePlayer } from "@/context/PlayerContext";

const poolCache = new Map<string, string[]>();
/** Videos YouTube refused to embed (error 101/150) — never picked again. */
const failedIds = new Set<string>();
const STATIC_RE = /\b(official audio|audio only|visuali[sz]er|lyric|lyrics|topic|full album|slowed|reverb|sped up|8d|nightcore|instrumental|karaoke|stream|cover art|static|album art|provided to youtube|art track|audio)\b/i;

/** True when a search result looks like a still-image upload rather than a real video. */
function looksStatic(v: any): boolean {
  const title = String(v?.title || v?.snippet?.title || "");
  const channel = String(v?.channelTitle || v?.uploader || v?.uploaderName || v?.snippet?.channelTitle || "");
  const desc = String(v?.description || v?.shortDescription || v?.snippet?.description || "");
  if (STATIC_RE.test(title)) return true;
  if (/-\s*topic$/i.test(channel.trim())) return true;
  if (/provided to youtube|auto-generated by youtube/i.test(desc)) return true;
  const dur = Number(v?.duration || v?.lengthSeconds || 0);
  if (dur > 0 && (dur < 60 || dur > 900)) return true;
  return false;
}

export function splitArtists(artist: string): string[] {
  return artist
    .split(/\s*(?:,|&|\bfeat\.?|\bft\.?|\bfeaturing\b|\bx\b|\bwith\b|\/)\s*/i)
    .map((a) => a.trim())
    .filter(Boolean)
    .slice(0, 3);
}

function idOf(v: any): string {
  return v?.videoId || v?.id?.videoId || (typeof v?.id === "string" ? v.id : "") || v?.url?.split("v=")[1] || "";
}

async function artistPool(artist: string): Promise<string[]> {
  const names = splitArtists(artist);
  if (!names.length) return [];
  const key = names.join("|").toLowerCase();
  if (poolCache.has(key)) return poolCache.get(key)!;
  const queries = names.length > 1
    ? [`${names.join(" ")} official music video`, ...names.map((n) => `${n} official music video`)]
    : [`${names[0]} official music video`];
  const results = await Promise.all(queries.map((q) => searchYouTubeVideos(q, 12).catch(() => [] as any[])));
  const firsts = names.map((n) => n.toLowerCase().split(" ")[0]);
  const ids = new Set<string>();
  for (const v of results.flat() as any[]) {
    const t = `${v.title || v.snippet?.title || ""} ${v.channelTitle || v.uploader || v.snippet?.channelTitle || ""}`.toLowerCase();
    if (looksStatic(v)) continue;
    if (!firsts.some((f) => t.includes(f))) continue;
    const id = idOf(v);
    if (id && !failedIds.has(id)) ids.add(id);
  }
  const pool = [...ids];
  if (pool.length) poolCache.set(key, pool);
  return pool;
}

const lastPicked = new Map<string, string>();
async function pickArtistVideo(artist: string): Promise<string> {
  const pool = (await artistPool(artist)).filter((id) => !failedIds.has(id));
  if (!pool.length) return "";
  const key = artist.toLowerCase();
  const options = pool.length > 1 ? pool.filter((id) => id !== lastPicked.get(key)) : pool;
  const id = options[Math.floor(Math.random() * options.length)];
  lastPicked.set(key, id);
  return id;
}

function cleanTitle(title: string): string {
  return title
    .replace(/\s*[([][^)\]]*[)\]]/g, "")
    .replace(/\s*(?:feat\.?|ft\.?|featuring)\s.*$/i, "")
    .replace(/\s+-\s+.*$/, "")
    .trim() || title;
}

const songCache = new Map<string, string>();
/** First real (non-static) video matching the song and an artist name. */
async function firstMatch(query: string, songWords: string[], firsts: string[]): Promise<string> {
  const res = (await searchYouTubeVideos(query, 10).catch(() => [])) as any[];
  for (const v of res) {
    const t = `${v.title || v.snippet?.title || ""} ${v.channelTitle || v.uploader || v.snippet?.channelTitle || ""}`.toLowerCase();
    if (looksStatic(v)) continue;
    if (songWords.length && !songWords.some((w) => t.includes(w))) continue;
    if (!firsts.some((f) => t.includes(f))) continue;
    const id = idOf(v);
    if (id && !failedIds.has(id)) return id;
  }
  return "";
}

/**
 * Video cascade: song music video -> fan-made video -> both artists' video ->
 * artist Vevo video -> random video from the artist's pool (last resort).
 */
async function pickVideo(title: string, artist: string): Promise<string> {
  const names = splitArtists(artist);
  if (!names.length) return "";
  const song = cleanTitle(title);
  const key = `${song}|${artist}`.toLowerCase();
  const cached = songCache.get(key);
  if (cached && !failedIds.has(cached)) return cached;
  const firsts = names.map((n) => n.toLowerCase().split(" ")[0]);
  const words = song.toLowerCase().split(/\s+/).filter((w) => w.length > 2).slice(0, 3);
  // Step 1 (unchanged): the song's own music video.
  if (song) {
    const id = await firstMatch(`${song} ${names[0]} music video`, words, firsts);
    if (id) { songCache.set(key, id); return id; }
  }
  // Step 2: any version of this song — Vevo, official, fan-made, edits.
  // Song + artist must be in the title; uploader channel doesn't matter.
  if (song) {
    const queries = [
      `${song} ${names[0]} vevo`,
      `${song} ${names[0]} official video`,
      `${song} ${names[0]} fan made video`,
      `${song} ${names[0]} edit`,
      `${song} ${names[0]} cinematic video`,
      ...(names.length > 1 ? [`${song} ${names.join(" ")} video`] : []),
    ];
    const results = await Promise.all(queries.map((q) => searchYouTubeVideos(q, 10).catch(() => [] as any[])));
    for (const list of results) {
      for (const v of list as any[]) {
        const t = String(v.title || v.snippet?.title || "").toLowerCase();
        if (looksStatic(v)) continue;
        if (words.length && !words.some((w) => t.includes(w))) continue;
        if (!firsts.some((f) => t.includes(f))) continue;
        const id = idOf(v);
        if (id && !failedIds.has(id)) { songCache.set(key, id); return id; }
      }
    }
  }
  // Step 3 (last resort): random video from the artist's pool.
  return pickArtistVideo(artist);
}

interface Props {
  trackId: string;
  artwork: string;
  videoId?: string;
  artist?: string;
  title?: string;
  enabled?: boolean;
  className?: string;
  onActiveChange?: (active: boolean) => void;
}

const usePlayerPlaying = { current: false };

export function VideoCanvas({ trackId, artwork, artist = "", title = "", enabled = true, className, onActiveChange }: Props) {
  const [id, setId] = useState("");
  const [retry, setRetry] = useState(0);

  // Always use the artist's official music videos — never the audio stream ID,
  // which is usually a static/visualizer upload.
  useEffect(() => {
    let cancelled = false;
    setId("");
    if (artist && enabled) {
      pickVideo(title, artist).then((v) => { if (!cancelled) setId(v); });
    }
    return () => { cancelled = true; };
  }, [trackId, artist, title, enabled, retry]);

  const active = enabled && !!id;
  // Hide the frame until YouTube's own start-up buttons have gone away.
  const [ready, setReady] = useState(false);
  useEffect(() => { setReady(false); if (!id) return; const t = window.setTimeout(() => setReady(true), 2500); return () => window.clearTimeout(t); }, [id]);
  // Listen to the embed: if YouTube refuses to play it (blocked/removed) or it
  // never starts, drop it and pick the next video so the canvas is never black.
  const playingRef = useRef(false);
  useEffect(() => {
    if (!id) return;
    playingRef.current = false;
    const fail = () => { failedIds.add(id); setId(""); setRetry((r) => r + 1); };
    const onMsg = (e: MessageEvent) => {
      if (typeof e.origin !== "string" || !e.origin.includes("youtube")) return;
      let d: any; try { d = typeof e.data === "string" ? JSON.parse(e.data) : e.data; } catch { return; }
      if (d?.event === "onError") fail();
      const state = d?.info?.playerState ?? (d?.event === "onStateChange" ? d.info : undefined);
      if (state === 1) { playingRef.current = true; setReady(true); }
    };
    window.addEventListener("message", onMsg);
    const watchdog = window.setTimeout(() => { if (!playingRef.current && usePlayerPlaying.current) fail(); }, 12000);
    return () => { window.removeEventListener("message", onMsg); window.clearTimeout(watchdog); };
  }, [id]);
  useEffect(() => { onActiveChange?.(active); }, [active, onActiveChange]);

  // Simple playback: the video just loops, pausing/playing with the song.
  const { isPlaying } = usePlayer();
  usePlayerPlaying.current = isPlaying;
  const frameRef = useRef<HTMLIFrameElement>(null);
  const send = (func: string, args: unknown[] = []) =>
    frameRef.current?.contentWindow?.postMessage(JSON.stringify({ event: "command", func, args }), "*");
  useEffect(() => {
    if (!ready) return;
    send(isPlaying ? "playVideo" : "pauseVideo");
  }, [isPlaying, ready]);

  return (
    <div aria-hidden className={cn("pointer-events-none absolute inset-0 overflow-hidden select-none [container-type:size]", className)}>
      {artwork && <img src={artwork} alt="" className="absolute inset-0 h-full w-full scale-110 object-cover blur-2xl opacity-60" />}
      {active && (
        <iframe
          ref={frameRef}
          key={id}
          title="canvas"
          tabIndex={-1}
          src={`https://www.youtube.com/embed/${id}?autoplay=1&mute=1&controls=0&loop=1&playlist=${id}&modestbranding=1&playsinline=1&rel=0&iv_load_policy=3&disablekb=1&fs=0&cc_load_policy=0&enablejsapi=1&origin=${encodeURIComponent(window.location.origin)}`}
          allow="autoplay; encrypted-media; picture-in-picture"
          onLoad={() => {
            // Subscribe to player events (errors / state) from the embed.
            frameRef.current?.contentWindow?.postMessage(JSON.stringify({ event: "listening", id: 1, channel: "widget" }), "*");
            send("addEventListener", ["onError"]);
            send("addEventListener", ["onStateChange"]);
            send("mute");
            if (usePlayerPlaying.current) send("playVideo");
          }}
          className={cn("pointer-events-none absolute left-1/2 top-1/2 aspect-video min-h-full min-w-full -translate-x-1/2 -translate-y-1/2 scale-[1.15] transition-opacity duration-1000", ready ? "opacity-100" : "opacity-0")}
          style={{ width: "max(100%, 177.78cqh)", height: "max(100%, 56.25cqw)" }}
        />
      )}
      <div className="absolute inset-0 bg-gradient-to-b from-background/30 via-transparent to-background/90" />
    </div>
  );
}
